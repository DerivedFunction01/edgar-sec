"""Root README generated-section synchronization.

Renders the layer roster, the check.py gate surface, and the entry-point
table from the tree itself into the root README's AUTOGEN sentinels.
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
import tomllib
from pathlib import Path

LAYERS_START = "<!-- AUTOGEN:LAYERS:START -->"
LAYERS_END = "<!-- AUTOGEN:LAYERS:END -->"
GATE_START = "<!-- AUTOGEN:GATE:START -->"
GATE_END = "<!-- AUTOGEN:GATE:END -->"
ENTRYPOINTS_START = "<!-- AUTOGEN:ENTRYPOINTS:START -->"
ENTRYPOINTS_END = "<!-- AUTOGEN:ENTRYPOINTS:END -->"

GENERATED_NOTE = (
    "<!-- generated by edgar_sec.tools.docgen.root_readme; "
    "regenerate: .venv/bin/python -m edgar_sec.tools.docgen.root_readme --fix -->"
)

_LAYERS_RE = re.compile(
    rf"({re.escape(LAYERS_START)}).*?({re.escape(LAYERS_END)})",
    re.DOTALL,
)
_GATE_RE = re.compile(
    rf"({re.escape(GATE_START)}).*?({re.escape(GATE_END)})",
    re.DOTALL,
)
_ENTRYPOINTS_RE = re.compile(
    rf"({re.escape(ENTRYPOINTS_START)}).*?({re.escape(ENTRYPOINTS_END)})",
    re.DOTALL,
)
_LAYER_PREFIX_RE = re.compile(r"^Layer \d+: ")

LAYERS = (
    (0, "foundation"),
    (1, "domain"),
    (2, "infra"),
    (3, "engine"),
    (4, "pipelines"),
    (5, "apps"),
    (6, "tools"),
)

ROOT_SCRIPTS = ("check.py", "run.py", "init_venv.py")


def _first_docstring_line(path: Path) -> str:
    """Return the first line of a module's docstring, or an em dash."""
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except (OSError, SyntaxError, ValueError):
        return "—"
    doc = ast.get_docstring(tree)
    if not doc:
        return "—"
    return doc.splitlines()[0].strip()


def _layer_summary(readme: Path) -> str:
    """Extract the summary after the em dash in a layer README title."""
    try:
        title = readme.read_text(encoding="utf-8").splitlines()[0]
    except (OSError, IndexError):
        return "—"
    if " — " not in title:
        return "—"
    summary = title.split(" — ", 1)[1].strip()
    return _LAYER_PREFIX_RE.sub("", summary)


def render_layers(repo_root: Path) -> str:
    """Render the layer table: one row per layer, subpackages linked."""
    rows = [
        "| Layer | Purpose (from its README) | Packages |",
        "| :--- | :--- | :--- |",
    ]
    for number, name in LAYERS:
        layer_dir = repo_root / "edgar_sec" / name
        if not layer_dir.is_dir():
            continue
        summary = _layer_summary(layer_dir / "README.md")
        packages = []
        for child in sorted(layer_dir.iterdir()):
            if not (child.is_dir() and (child / "__init__.py").exists()):
                continue
            rel = f"edgar_sec/{name}/{child.name}"
            target = f"{rel}/README.md" if (child / "README.md").exists() else rel
            packages.append(f"[`{child.name}`]({target})")
        joined = ", ".join(packages) if packages else "—"
        rows.append(f"| {number} — `{name}/` | {summary} | {joined} |")
    return "\n".join(rows)


def _argument_rows(check_py: Path) -> list[tuple[str, str]]:
    """Extract (argument, help) pairs from check.py's parser in order."""
    tree = ast.parse(check_py.read_text(encoding="utf-8"))
    main_fn = next(
        (n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "main"),
        None,
    )
    if main_fn is None:
        return []
    rows: list[tuple[str, str]] = []
    for node in ast.walk(main_fn):
        if not isinstance(node, ast.Call):
            continue
        func = node.func
        if not (isinstance(func, ast.Attribute) and func.attr == "add_argument"):
            continue
        flags = [
            a.value
            for a in node.args
            if isinstance(a, ast.Constant) and isinstance(a.value, str)
        ]
        if not flags:
            continue
        help_text = "—"
        for kw in node.keywords:
            if kw.arg == "help" and isinstance(kw.value, ast.Constant):
                help_text = str(kw.value.value)
        label = ", ".join(f"`{flag}`" for flag in flags if flag.startswith("-"))
        if not label:
            label = f"`{flags[0]}` (positional)"
        rows.append((label, help_text))
    return rows


def render_gate(repo_root: Path) -> str:
    """Render check.py's argument surface as a table from its AST."""
    rows = ["| Argument | Description |", "| :--- | :--- |"]
    for label, help_text in _argument_rows(repo_root / "check.py"):
        rows.append(f"| {label} | {help_text.replace('|', chr(92) + '|')} |")
    return "\n".join(rows)


def render_entrypoints(repo_root: Path) -> str:
    """Render console scripts from pyproject.toml and root scripts."""
    rows = ["| Entry point | Target | Description |", "| :--- | :--- | :--- |"]
    try:
        data = tomllib.loads((repo_root / "pyproject.toml").read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError):
        data = {}
    scripts = data.get("project", {}).get("scripts", {})
    for name in sorted(scripts):
        target = scripts[name]
        module_path = target.split(":")[0].replace(".", "/") + ".py"
        desc = _first_docstring_line(repo_root / module_path)
        rows.append(f"| `{name}` | `{target}` | {desc} |")
    for script in ROOT_SCRIPTS:
        path = repo_root / script
        if path.exists():
            desc = _first_docstring_line(path)
            rows.append(f"| `{script}` | repo root | {desc} |")
    return "\n".join(rows)


def sync_root_readme(
    readme_path: Path, repo_root: Path, apply: bool = False
) -> tuple[bool, str]:
    """Sync the root README's sentinels; return (in_sync, updated_text)."""
    text = readme_path.read_text(encoding="utf-8")
    original = text
    sections = (
        (_LAYERS_RE, render_layers(repo_root)),
        (_GATE_RE, render_gate(repo_root)),
        (_ENTRYPOINTS_RE, render_entrypoints(repo_root)),
    )
    for pattern, body in sections:
        if pattern.search(text):
            text = pattern.sub(
                lambda m: f"{m.group(1)}\n{GENERATED_NOTE}\n{body}\n{m.group(2)}",
                text,
            )
    in_sync = text == original
    if not in_sync and apply:
        readme_path.write_text(text, encoding="utf-8")
    return in_sync, text


def main(argv: list[str] | None = None) -> int:
    """CLI dispatcher for root README sentinel verification and updates."""
    parser = argparse.ArgumentParser(description="Root README docgen tool.")
    parser.add_argument("--check", action="store_true", help="Verify sentinels.")
    parser.add_argument("--fix", action="store_true", help="Update sentinels in place.")
    parser.add_argument("--repo-root", default=".", help="Repository root path.")
    args = parser.parse_args(argv)

    root = Path(args.repo_root).resolve()
    in_sync, _ = sync_root_readme(root / "README.md", root, apply=args.fix)
    if in_sync:
        print("==> root README sentinels in sync")
        return 0
    if args.fix:
        print("==> root README updated successfully.")
        return 0
    print("==> root README drifted. Run with --fix to update.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
